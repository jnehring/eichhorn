"""Generate reference docs and check examples (used by CI, spec 11.7).

python -m eichhorn._docs cli              > docs/cli.md
python -m eichhorn._docs config           > docs/configuration-reference.md
python -m eichhorn._docs check-examples examples
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

from eichhorn import schema
from eichhorn.cli import build_parser
from eichhorn.yamlload import load_file

PIPE = "\\|"  # a | inside a Markdown table cell
HEADER = "<!-- Generated by `python -m eichhorn._docs {what}`. Do not edit by hand. -->\n\n"


def _subparsers(p: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    for action in p._actions:
        if isinstance(action, argparse._SubParsersAction):
            return dict(action.choices)
    return {}


def _help(p: argparse.ArgumentParser, parent: argparse.ArgumentParser, name: str) -> str:
    for action in parent._actions:
        if isinstance(action, argparse._SubParsersAction):
            for choice in action._choices_actions:
                if choice.dest == name:
                    return choice.help or ""
    return p.description or ""


def cli_markdown() -> str:
    root = build_parser()
    out = [HEADER.format(what="cli"), "# Command reference\n\n"]
    out.append(
        "Every command and option of `eichhorn`. For a guided start see "
        "[Getting started](getting-started.md).\n\n"
    )
    out.append("## Global options\n\n```text\n" + root.format_usage().strip() + "\n```\n\n")
    out.append(_options_table(root))

    def walk(p: argparse.ArgumentParser, parent: argparse.ArgumentParser, path: list[str]) -> None:
        subs = _subparsers(p)
        if not subs:
            out.append(f"## `eichhorn {' '.join(path)}`\n\n")
            text = _help(p, parent, path[-1])
            if text:
                out.append(text[0].upper() + text[1:] + ".\n\n")
            usage = p.format_usage().replace("usage: ", "").strip()
            out.append("```text\n" + " ".join(usage.split()) + "\n```\n\n")
            out.append(_options_table(p))
            return
        for name, sp in subs.items():
            walk(sp, p, [*path, name])

    for name, sp in _subparsers(root).items():
        walk(sp, root, [name])
    out.append("---\n\n[Back to the docs index](README.md)\n")
    return "".join(out)


def _options_table(p: argparse.ArgumentParser) -> str:
    rows = []
    for a in p._actions:
        if isinstance(a, (argparse._SubParsersAction, argparse._HelpAction)):
            continue
        if a.option_strings:
            name = ", ".join(f"`{o}`" for o in a.option_strings)
            if a.metavar or (a.nargs != 0 and not isinstance(a.const, bool)):
                if a.choices:
                    name += " `" + PIPE.join(a.choices) + "`"
                elif a.nargs != 0:
                    name += f" `{a.metavar or a.dest.upper()}`"
        else:
            name = f"`{a.metavar or a.dest}`"
        text = (a.help or "").replace("|", PIPE)
        rows.append(f"| {name} | {text} |")
    if not rows:
        return ""
    return "| Argument | Meaning |\n|---|---|\n" + "\n".join(rows) + "\n\n"


def _fields_table(fields: tuple[schema.Field, ...], prefix: str = "") -> list[str]:
    rows = []
    for f in fields:
        key = f"`{prefix}{f.name}`"
        default = "" if f.default is None else f"`{str(f.default).lower()}`"
        kind = f.kind + (" (" + " \\| ".join(f.choices) + ")" if f.choices else "")
        doc = f.doc + (" **Required.**" if f.required else "")
        if f.milestone:
            doc += f" *(Implemented in milestone {f.milestone}.)*"
        rows.append(f"| {key} | {kind} | {default} | {doc} |")
        if f.fields:
            sub = f"{prefix}{f.name}[]." if f.kind == "list[map]" else f"{prefix}{f.name}."
            rows += _fields_table(f.fields, sub)
    return rows


def config_markdown() -> str:
    head = "| Key | Type | Default | Meaning |\n|---|---|---|---|\n"
    return (
        HEADER.format(what="config") + "# Configuration reference\n\n"
        "All keys of the configuration files, generated from the schema that Eichhorn "
        "uses to check them. For explanations and examples see "
        "[Configuration](configuration.md).\n\n"
        "## `eichhorn.yaml` and `repositories.yaml`\n\n"
        + head
        + "\n".join(_fields_table(schema.GLOBAL_SCHEMA))
        + "\n\n## `targets/<name>.yaml`\n\n"
        + head
        + "\n".join(_fields_table(schema.TARGET_SCHEMA))
        + "\n\n---\n\n[Back to the docs index](README.md)\n"
    )


def check_examples(directory: Path) -> int:
    problems: list[str] = []
    files = sorted(directory.rglob("*.yaml"))
    for f in files:
        doc = load_file(f)
        target = f.parent.name == "targets"
        problems += schema.validate(doc, schema.TARGET_SCHEMA if target else schema.GLOBAL_SCHEMA)
    for p in problems:
        print(p)
    print(f"{len(files)} example file(s) checked, {len(problems)} problem(s)")
    return 1 if problems else 0


def main() -> int:
    os.environ["COLUMNS"] = "100"  # stable usage lines, whatever the terminal
    what = sys.argv[1] if len(sys.argv) > 1 else ""
    if what == "cli":
        sys.stdout.write(cli_markdown())
    elif what == "config":
        sys.stdout.write(config_markdown())
    elif what == "check-examples":
        return check_examples(Path(sys.argv[2] if len(sys.argv) > 2 else "examples"))
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
